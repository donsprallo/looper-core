"""A description of one simulation build, for another build system to read.

CMake has to know which files a target is made of before it writes a build
graph, and two of the three answers are things it cannot work out: which
sources the generator produced depends on which adapter headers exist, and
which firmware sources take part is written down in the build definition.

Writing both out means a CMake project says where its definition is and
nothing else. The alternative is repeating eighteen source directories and
seven exclusions in a second language, which is two places to change and
one of them will be forgotten.

Rendered here rather than from a template: the content is a list of paths,
not a document with a shape.
"""

from __future__ import annotations

from pathlib import Path

from looper import __version__
from looper.domain.model.build import SimulationBuildDefinition
from looper.infrastructure.build.instrumentation import (
    allocation_link_options,
    instrumentation_options,
)
from looper.infrastructure.build.project_sources import (
    generated_sources,
    include_directories,
    project_sources,
)

MANIFEST_NAME = "looper_generated.cmake"

HEADER = """\
# Generated by looper {version}. Do not edit.
#
# What this simulation is made of, as the build definition and the generator
# together describe it. A build system reads this instead of repeating the
# definition in its own language.
"""


def render_cmake_manifest(definition: SimulationBuildDefinition) -> str:
    """Describe a build definition as CMake variables.

    Args:
        definition: The build, with its generated sources already written.

    Returns:
        The complete content of the manifest file.
    """
    blocks = (
        HEADER.format(version=__version__),
        _list("LOOPER_GENERATED_SOURCES", generated_sources(definition)),
        _list("LOOPER_PROJECT_SOURCES", project_sources(definition)),
        _list("LOOPER_INCLUDE_DIRECTORIES", include_directories(definition)),
        _strings("LOOPER_COMPILE_DEFINITIONS", definition.all_definitions),
        _strings("LOOPER_COMPILE_OPTIONS", definition.warning_flags),
        _strings("LOOPER_INSTRUMENT_OPTIONS", instrumentation_options(definition)),
        _strings("LOOPER_LINK_OPTIONS", allocation_link_options(definition)),
        _strings("LOOPER_C_STANDARD", (definition.language_standard.removeprefix("c"),)),
    )
    return "\n".join(blocks)


def _list(name: str, paths: tuple[Path, ...]) -> str:
    """Render a CMake list of paths.

    Forward slashes throughout: CMake reads a backslash as an escape, and a
    Windows path written with them arrives as something else entirely.
    """
    return _strings(name, tuple(path.as_posix() for path in paths))


def _strings(name: str, values: tuple[str, ...]) -> str:
    """Render a CMake list of plain strings.

    Backslashes are escaped. CMake reads one as the start of an escape
    sequence, so a Windows path inside a quoted argument is a syntax
    error before it is anything else.
    """
    if not values:
        return f"set({name})\n"
    entries = "\n".join(f'    "{_escaped(value)}"' for value in values)
    return f"set({name}\n{entries}\n)\n"


def _escaped(value: str) -> str:
    """One string as CMake has to read it back."""
    return value.replace("\\", "\\\\").replace('"', '\\"')


def write_cmake_manifest(definition: SimulationBuildDefinition) -> Path:
    """Write the manifest next to the sources the generator produced.

    Called after generation, because what the generator wrote is part of
    what the manifest says. Not a use case of its own: there is no decision
    in it, only a definition rendered in another language.

    Args:
        definition: The build, with its generated sources already written.

    Returns:
        The file that was written.
    """
    path = definition.generated_directory / MANIFEST_NAME
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_cmake_manifest(definition), encoding="utf-8")
    return path
